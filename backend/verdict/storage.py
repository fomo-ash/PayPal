"""Blob storage for suites, reference solutions and submissions.

LocalBlobStore writes under a directory (dev, tests, single-box demo). DbBlobStore keeps blobs
in Postgres, for hosts where processes do not share a disk (BLOB_BACKEND=db). An R2/S3 store
with the same two methods can replace either without touching callers. Keys are generated by our
code only (never from user input), and are checked anyway so a bad key can never escape the root.
"""

from __future__ import annotations

import os
import re
import tempfile
from pathlib import Path
from typing import Protocol

KEY = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*(/[A-Za-z0-9][A-Za-z0-9._-]*)*")


class BlobStore(Protocol):
    def put(self, key: str, data: bytes) -> None: ...
    def get(self, key: str) -> bytes: ...


class LocalBlobStore:
    def __init__(self, root: str | Path):
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        if not KEY.fullmatch(key) or ".." in key.split("/"):
            raise ValueError(f"bad blob key {key!r}")
        return self.root / key

    def put(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        # write to a temp file and rename, so a reader never sees half a file
        fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".tmp-")
        try:
            with os.fdopen(fd, "wb") as f:
                f.write(data)
            os.replace(tmp, path)
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise

    def get(self, key: str) -> bytes:
        return self._path(key).read_bytes()


class DbBlobStore:
    def __init__(self, Session):  # noqa: N803 - a session factory
        self.Session = Session

    def put(self, key: str, data: bytes) -> None:
        from verdict.db.models import Blob
        if not KEY.fullmatch(key) or ".." in key.split("/"):
            raise ValueError(f"bad blob key {key!r}")
        with self.Session.begin() as s:
            s.merge(Blob(key=key, data=data))

    def get(self, key: str) -> bytes:
        from verdict.db.models import Blob
        with self.Session() as s:
            row = s.get(Blob, key)
            if row is None:
                raise FileNotFoundError(key)
            return row.data


def make_store(cfg, Session) -> BlobStore:  # noqa: N803
    if cfg.blob_backend == "db":
        return DbBlobStore(Session)
    if cfg.blob_backend != "local":
        raise ValueError("BLOB_BACKEND must be 'local' or 'db'")
    return LocalBlobStore(cfg.blob_dir)
